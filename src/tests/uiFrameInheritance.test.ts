import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {promises as fs} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

test('public MCP inherits Core containers through Frame and edits typed children without unknown-property overrides', {timeout:30000}, async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'sc2-frame-template-'));
  const child=spawn(process.execPath,['dist/index.js'],{env:{...process.env,SC2_UI_ROOT:root,SC2_MCP_PROFILE:'ui',SC2_MCP_MODULES:''},windowsHide:true,stdio:['pipe','pipe','pipe']});
  let buffer='',stderr='',id=0;
  const pending=new Map<number,{resolve:(value:any)=>void;reject:(error:Error)=>void}>();
  const closed=new Promise<void>(resolve=>child.once('close',()=>resolve()));
  child.stderr.on('data',data=>{stderr+=data;});
  child.stdout.on('data',data=>{buffer+=data;let end:number;while((end=buffer.indexOf('\n'))>=0){const line=buffer.slice(0,end);buffer=buffer.slice(end+1);const value=JSON.parse(line),p=pending.get(value.id);if(p){pending.delete(value.id);value.error?p.reject(Error(JSON.stringify(value.error))):p.resolve(value.result);}}});
  child.once('exit',()=>{for(const p of pending.values())p.reject(Error('Owned UI server exited: '+stderr));pending.clear();});
  t.after(async()=>{child.stdin.end();await closed;await fs.rm(root,{recursive:true,force:true});});
  const rpc=(method:string,params:unknown)=>new Promise<any>((resolve,reject)=>{const n=++id;pending.set(n,{resolve,reject});child.stdin.write(JSON.stringify({jsonrpc:'2.0',id:n,method,params})+'\n');});
  const tool=async(name:string,args:unknown)=>{const result=await rpc('tools/call',{name,arguments:args});assert.notEqual(result.isError,true,JSON.stringify(result));return JSON.parse(result.content[0].text);};
  await rpc('initialize',{protocolVersion:'2025-11-25',capabilities:{},clientInfo:{name:'Frame inheritance regression',version:'1'}});
  child.stdin.write(JSON.stringify({jsonrpc:'2.0',method:'notifications/initialized'})+'\n');
  const file='UI/Layout/Video.SC2Layout';
  await tool('ui.create_file',{file,kind:'layout',dryRun:false});
  const created=await tool('ui.create_from_blizzard_template',{file,type:'Frame',name:'MovieContainer',template:'CommanderSelectionPopupContainers/MovieContainerTemplate',dryRun:false});
  assert.equal(created.templateUsage.classCompatible,true);
  await tool('ui.create_frame',{file,parentPath:'MovieContainer',type:'Frame',name:'MovieFrame',properties:[{tag:'Loop',value:true}],dryRun:false});
  const automatic=await tool('ui.create_restricted_frame',{file,type:'MovieFrame',name:'AutomaticMovie',properties:[{tag:'Loop',value:true}],dryRun:false});
  assert.equal(automatic.construction,'inherited-frame');
  assert.equal(automatic.created.runtimeTargetPath,'AutomaticMovie/MovieFrame');
  await tool('ui.create_restricted_frame',{file,type:'SceneBrowser',name:'AutomaticBrowser',properties:[{tag:'Address',value:'https://example.invalid'}],dryRun:false});
  await tool('ui.set_property',{file,framePath:'MovieContainer/MovieFrame',property:'Loop',value:false,dryRun:false});
  const rejected=await rpc('tools/call',{name:'ui.set_property',arguments:{file,framePath:'MovieContainer/MovieFrame',property:'Loop',value:'invalid',dryRun:false}});
  assert.equal(rejected.isError,true);
  await tool('ui.save',{file});
  const saved=await fs.readFile(path.join(root,file),'utf8');
  assert.match(saved,/type="Frame" name="MovieContainer"/);
  assert.match(saved,/<Loop val="false"\/>/);
  assert.doesNotMatch(saved,/<Loop val="invalid"/);
  assert.match(saved,/type="Frame" name="AutomaticMovie"/);
  assert.match(saved,/type="Frame" name="SceneBrowser"/);
  assert.doesNotMatch(saved,/type="(?:MovieFrame|SceneBrowser|SceneBrowserDialog)"/);
});
